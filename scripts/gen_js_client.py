"""Write js/src/generated.ts, the JavaScript client's table of web API operations, from the server's own routes.

    python scripts/gen_js_client.py          # rewrite the file
    python scripts/gen_js_client.py --check  # exit 1 if it is out of date (tests/test_js_client.py does this too)

Each service operation the web API exposes ("runs.run_transcript") becomes a typed method of the client's `api`
object (dyno.api.runs.runTranscript({ rid })), from the same table the Python library uses for remote calls, so the
two clients can't drift apart. The profile setting names come along, so cloudModel() rejects the same typos.
"""
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "js" / "src" / "generated.ts"
sys.path.insert(0, str(ROOT))


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def ts_type(field) -> str:
    ann = getattr(getattr(field, "field_info", None), "annotation", None)
    text = str(ann)
    if ann is bool or "bool" in text:
        return "boolean"
    if ann in (int, float) or "int" in text or "float" in text:
        return "number"
    return "string"


def fields_by_route():
    """(METHOD, path) -> {param: (required, ts type)} for the server's routes."""
    from fastapi.routing import APIRoute

    from llmdyno.server import app
    out = {}
    for r in app.routes:
        if not isinstance(r, APIRoute):
            continue
        info = {}
        for p in r.dependant.path_params:
            info[p.name] = (True, "string")
        for p in r.dependant.query_params:
            info[p.name] = (bool(p.required), ts_type(p))
        for p in r.dependant.body_params:
            info[p.name] = (bool(p.required), "Record<string, unknown>")
        for m in r.methods - {"HEAD"}:
            out[(m, r.path)] = info
    return out


def render() -> str:
    os.environ.setdefault("LLMDYNO_DATA", tempfile.mkdtemp(prefix="llmdyno-gen-"))
    from llmdyno.sdk import parity
    from llmdyno.sdk.profiles import CLOUD_PARAM_NAMES, LOCAL_PARAM_NAMES, SAMPLING_NAMES
    from llmdyno.sdk.remote import route_table

    routes = route_table()
    fields = fields_by_route()
    coverage = parity.coverage()
    areas: dict[str, list[str]] = {}
    lines = [
        "// Generated by scripts/gen_js_client.py from the LLMDyno server's routes. Do not edit by hand: run",
        "// `python scripts/gen_js_client.py` after changing the web API (tests/test_js_client.py checks it is current).",
        "",
        'export type Where = "path" | "query" | "body" | "file";',
        "",
        "export interface Route {",
        "  readonly method: string;",
        "  readonly path: string;",
        "  readonly params: Readonly<Record<string, Where>>;",
        "}",
        "",
        "/** Every operation of the web API: the service name the Python library uses -> its HTTP route. */",
        "export const ROUTES = {",
    ]
    for op in sorted(routes):
        method, path, where = routes[op]
        params = ", ".join(f"{k}: {v!r}".replace("'", '"') for k, v in where.items())
        lines.append(f'  "{op}": {{ method: "{method}", path: "{path}", params: {{ {params} }} }},'
                     if params else f'  "{op}": {{ method: "{method}", path: "{path}", params: {{}} }},')
        areas.setdefault(op.split(".", 1)[0], []).append(op)
    lines += ["} as const satisfies Record<string, Route>;", "", "export type Operation = keyof typeof ROUTES;", ""]

    lines += ["/** The typed `api` object: one method per operation, grouped by area. */", "export interface Api {"]
    for area in sorted(areas):
        lines.append(f"  {area}: {{")
        for op in sorted(areas[area]):
            method, path, where = routes[op]
            info = fields.get((method, path), {})
            python = [n.replace("llmdyno.sdk.", "").split(".", 1)[-1] for n in coverage.get(f"{method} {path}", [])]
            doc = f"{method} {path}" + (f" · Python: llmdyno.{python[0]}" if python else "")
            props = []
            for k, kind in where.items():
                if kind == "file":
                    props.append(f"{k}: Blob | Uint8Array | ArrayBuffer")
                    continue
                required, typ = info.get(k, (False, "string"))
                props.append(f"{k}{'' if required else '?'}: {typ}")
            needs = any(not p.split(":")[0].endswith("?") for p in props)
            arg = f"params{'' if needs else '?'}: {{ {'; '.join(props)} }}" if props else ""
            lines.append(f"    /** {doc} */")
            lines.append(f"    {camel(op.split('.', 1)[1])}({arg}): Promise<any>;")
        lines.append("  };")
    lines += ["}", ""]

    lines.append("/** area -> method name -> operation, used to build the `api` object at runtime. */")
    lines.append("export const API_METHODS: Readonly<Record<string, Readonly<Record<string, Operation>>>> = {")
    for area in sorted(areas):
        pairs = ", ".join(f'{camel(op.split(".", 1)[1])}: "{op}"' for op in sorted(areas[area]))
        lines.append(f"  {area}: {{ {pairs} }},")
    lines += ["};", ""]

    def names(values) -> str:
        return ", ".join(f'"{v}"' for v in sorted(values))
    lines += [
        "/** Profile settings a cloud model accepts (cloudModel() options beyond the documented ones). */",
        f"export const CLOUD_PARAMS: readonly string[] = [{names(CLOUD_PARAM_NAMES)}];",
        "/** Profile settings a local (llama.cpp) model accepts. */",
        f"export const LOCAL_PARAMS: readonly string[] = [{names(LOCAL_PARAM_NAMES)}];",
        "/** Sampling settings of a local model, stored under params.sampling. */",
        f"export const SAMPLING_PARAMS: readonly string[] = [{names(SAMPLING_NAMES)}];",
        "",
    ]
    text = "\n".join(lines)
    return re.sub(r"[ \t]+\n", "\n", text)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_js_client.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
