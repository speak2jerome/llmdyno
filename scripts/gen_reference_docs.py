"""Write the generated reference pages of the docs site from the code, so they can't fall behind it.

    python scripts/gen_reference_docs.py          # rewrite the pages
    python scripts/gen_reference_docs.py --check  # exit 1 if a page is out of date (tests/test_docs_site.py does this too)

docs/reference/cli.md       every `llmdyno` command, its arguments and defaults, from the CLI parser itself.
docs/reference/web-api.md   every web API route with the Python call, the command and the JavaScript method that
                            reach it, from the server's routes, the library's parity map and the JS client's table.
"""
import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs" / "reference"
sys.path.insert(0, str(ROOT))

HEADER = ("<!-- Generated by scripts/gen_reference_docs.py from the code. Do not edit by hand: run "
          "`python scripts/gen_reference_docs.py` (tests/test_docs_site.py checks the page is current). -->")

# SDK module -> section title, in the order of the API reference pages
AREAS = {
    "_core": "Data folder",
    "system": "Setup, system and jobs",
    "profiles": "Profiles",
    "models": "Models",
    "providers": "Providers",
    "harnesses": "Harnesses",
    "agents": "Your own agent as a harness",
    "benchmarks": "Benchmarks and suites",
    "plans": "Plans",
    "runs": "Runs and transcripts",
    "results": "Results",
    "judging": "Judging",
    "live": "Live events",
    "references": "Artificial Analysis reference numbers",
    "settings": "Settings",
    "interop": "Interop and CI",
    "ui": "The dashboard",
}
COMMON = {"--json", "--data", "--url", "--api-token", "-h", "--help", "--version"}


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _kind(action: argparse.Action) -> str:
    if isinstance(action, argparse.BooleanOptionalAction):
        return "flag"
    if action.nargs == 0:
        return "flag"
    if action.type is json.loads:
        return "JSON"
    if action.type is int:
        return "integer"
    if action.type is float:
        return "number"
    if action.choices:
        return " / ".join(f"`{c}`" for c in action.choices)
    return "text"


def _default(action: argparse.Action) -> str:
    d = action.default
    if action.option_strings and isinstance(action, argparse.BooleanOptionalAction):
        return f"`--{'' if d else 'no-'}{action.dest.replace('_', '-')}`"
    if d in (None, argparse.SUPPRESS) or (action.nargs == 0 and d is False):
        return ""
    if isinstance(d, (list, tuple)):
        return "`" + " ".join(map(str, d)) + "`" if d else ""
    return f"`{d}`"


def _options(parser: argparse.ArgumentParser) -> list[str]:
    rows = []
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction) or COMMON & set(a.option_strings):
            continue
        if a.dest == "_set":
            name = "`--set KEY=VALUE`"
        elif a.option_strings:
            name = " / ".join(f"`{o}`" for o in a.option_strings)
        else:
            name = f"`{(a.metavar or a.dest).upper()}`"
        if a.nargs in ("+", "*"):
            kind = _kind(a) + (", one or more" if not a.option_strings else ", one or more values")
        else:
            kind = _kind(a) + (", repeatable" if a.dest == "_set" else "")
        if not a.option_strings:
            kind = "positional, " + kind
        elif a.required:
            kind += ", required"
        help_text = a.help or ""
        if a.dest == "_set":
            help_text = "a setting; the value is read as JSON when it parses"
        rows.append((name, kind, _default(a), _cell(help_text)))
    if not rows:
        return []
    if any(r[3] for r in rows):
        return ["| Argument | Type | Default | Description |", "|---|---|---|---|",
                *[f"| {n} | {k} | {d} | {h} |" for n, k, d, h in rows], ""]
    return ["| Argument | Type | Default |", "|---|---|---|", *[f"| {n} | {k} | {d} |" for n, k, d, _ in rows], ""]


def _synopsis(prog: str, parser: argparse.ArgumentParser) -> str:
    pos = [(a.metavar or a.dest).upper() + (" …" if a.nargs in ("+", "*") else "")
           for a in parser._actions if not a.option_strings and not isinstance(a, argparse._SubParsersAction)]
    has_opts = any(a.option_strings and not (COMMON & set(a.option_strings)) for a in parser._actions)
    return " ".join([prog, *pos] + (["[options]"] if has_opts else []))


def _subparsers(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            return dict(a.choices)
    return {}


def _description(parser: argparse.ArgumentParser, help_text: str) -> list[str]:
    text = (parser.description or help_text or "").strip()
    return [text, ""] if text else []


def render_cli() -> str:
    from llmdyno.cli import CUSTOM, GROUPS, build_parser
    ap, registry = build_parser()
    subs = _subparsers(ap)
    helps = {}
    for a in ap._actions:
        if isinstance(a, argparse._SubParsersAction):
            helps = {c.dest: c.help or "" for c in a._choices_actions}

    out = [HEADER, "", "# Command line", "",
           "Every library call is also a command, generated from the library itself, so this page and "
           "[the Python API](index.md) describe the same operations. Function names become commands with dashes "
           "(`llmdyno.search_models()` is `llmdyno search-models`), methods of an object become "
           "`llmdyno <object> <method> ID` (`Run.transcript()` is `llmdyno run transcript RUN_ID`), parameters "
           "without a default are positional and the rest are `--options`. Keyword settings, such as the profile "
           "settings of `cloud-model` and `local-model`, go in `--set key=value`, read as JSON when the value "
           "parses (`--set ctx=32768 --set thinking=true`).", "",
           "`llmdyno` on its own starts the web app, like `llmdyno serve`. `llmdyno --version` prints the version.",
           "", "## Options every command takes", "",
           "| Option | Description |", "|---|---|",
           "| `--json` | Machine-readable output: JSON, or one JSON object per line for streams such as `watch`. |",
           "| `--data DIR` | The data folder to use. Default: `LLMDYNO_DATA`, else the usual folder for your system. |",
           "| `--url URL` | Run the command on a LLMDyno server on another machine. Default: `LLMDYNO_URL`, else this "
           "machine. See [Remote mode](../REMOTE.md). |",
           "| `--api-token TOKEN` | That server's access token. Default: `LLMDYNO_TOKEN`. |",
           "| `-h`, `--help` | Show the command's help and exit. |", ""]

    def command(title_prog: str, parser: argparse.ArgumentParser, help_text: str, level: str = "###"):
        out.extend([f"{level} `{title_prog}`", ""])
        out.extend(_description(parser, help_text))
        out.extend(["```text", _synopsis(title_prog, parser), "```", ""])
        out.extend(_options(parser))

    out += ["## Server and maintenance", "",
            "Hand-written commands that are not library calls.", ""]
    for name in CUSTOM:
        command(f"llmdyno {name}", subs[name], helps.get(name, ""))

    by_area: dict[str, list[str]] = {}
    groups = {group for group, _ in GROUPS.values()}
    for name in subs:
        if name in CUSTOM or name in groups:
            continue
        fn = registry[name][0]
        area = fn.__module__.rsplit(".", 1)[-1]
        by_area.setdefault(area, []).append(name)
    unknown = set(by_area) - set(AREAS)
    if unknown:
        raise SystemExit(f"add {sorted(unknown)} to AREAS in scripts/gen_reference_docs.py")
    out += ["## Library calls", "", "One command per `llmdyno.<function>()`, grouped like the API reference.", ""]
    for area, title in AREAS.items():
        if area not in by_area:
            continue
        out += [f"### {title}", ""]
        for name in sorted(by_area[area]):
            command(f"llmdyno {name}", subs[name], helps.get(name, ""), "####")

    out += ["## Objects", "",
            "Commands for one object, by id (or by name, where names are unique). `show` prints everything about "
            "it; the other actions are its methods.", ""]
    for cls_name, (group, _getter) in GROUPS.items():
        gp = subs[group]
        out += [f"### `llmdyno {group}`", ""]
        out.extend(_description(gp, helps.get(group, "")))
        actions = _subparsers(gp)
        action_help = {}
        for a in gp._actions:
            if isinstance(a, argparse._SubParsersAction):
                action_help = {c.dest: c.help or "" for c in a._choices_actions}
        out += ["| Action | What it does |", "|---|---|"]
        out += [f"| [`{act}`](#llmdyno-{group}-{act}) | {_cell(action_help.get(act, ''))} |" for act in actions]
        out.append("")
        for act, p in actions.items():
            command(f"llmdyno {group} {act}", p, action_help.get(act, ""), "####")
    text = "\n".join(out).rstrip() + "\n"
    return re.sub(r"[ \t]+\n", "\n", text)


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def render_web_api() -> str:
    from llmdyno.cli import GROUPS, build_parser
    from llmdyno.sdk import parity
    from llmdyno.sdk.remote import route_table

    from llmdyno import lib
    from llmdyno.cli import CUSTOM

    def qualified_name(fn) -> str:
        return f"{getattr(fn, '__module__', '')}.{getattr(fn, '__qualname__', '')}"

    _, registry = build_parser()
    command_of = {}
    for cmd, (fn, _spec) in registry.items():
        if callable(fn):
            command_of.setdefault(qualified_name(fn), cmd)
    for group, getter in GROUPS.values():                   # llmdyno.run(ID) is `llmdyno run show ID`
        command_of.setdefault(qualified_name(getattr(lib, getter)), f"{group} show")
    for name in CUSTOM:                                     # doctor() and specs() have hand-written commands
        if hasattr(lib, name):
            command_of.setdefault(qualified_name(getattr(lib, name)), name)
    command_of.setdefault("llmdyno.sdk.results.Results.export", "results --export PATH")
    coverage = parity.coverage()

    def python(qualified: str) -> str:
        name = qualified.replace("llmdyno.sdk.", "").split(".", 1)[1]
        return f"`{name}()`" if "." in name else f"`llmdyno.{name}()`"

    def cli(qualified: str) -> str:
        cmd = command_of.get(qualified)
        owner, method = qualified.rsplit(".", 2)[-2:]
        if not cmd and method == "refresh" and owner in GROUPS:
            cmd = f"{GROUPS[owner][0]} show"        # an object's details: `llmdyno <object> show ID`
        return f"`llmdyno {cmd}`" if cmd else ""

    areas: dict[str, list[str]] = {}
    for op in route_table():
        areas.setdefault(op.split(".", 1)[0], []).append(op)
    out = [HEADER, "", "# Web API map", "",
           "Every operation of LLMDyno's web API, with the Python call, the command and the JavaScript method that "
           "reach it. The dashboard uses this API; so do the Python library in [remote mode](../REMOTE.md) and the "
           "[JavaScript client](../JAVASCRIPT.md). A test fails when a route has no library call, so the four columns "
           "can't drift apart.", "",
           "A running server also describes the API itself, from the same code:", "",
           "- `http://127.0.0.1:8777/docs`: interactive Swagger UI, where you can try each call.",
           "- `http://127.0.0.1:8777/redoc`: the same as a reference page.",
           "- `http://127.0.0.1:8777/openapi.json`: the OpenAPI 3 schema, for generating other clients.", "",
           "Requests from another machine need the access token, as `Authorization: Bearer TOKEN` or `?token=TOKEN` "
           "(see [Remote mode](../REMOTE.md)); without it the answer is 401. Errors come back as "
           "`{\"detail\": \"message\"}` with the HTTP status of the [library's error](errors.md): 400 invalid, "
           "403 forbidden, 404 not found, 409 conflict or failed preflight, 428 risk not acknowledged, "
           "429 rate limited, 502 upstream failure, 507 insufficient storage.", "",
           "Besides the operations below, the server answers:", "",
           "| Route | What it is |", "|---|---|",
           "| `GET /api/health` | Whether the server is up: `ok`, `version`, `schema_version`, `time` and `data_dir`. "
           "The library and the JS client call it when they connect. |",
           "| `WS /ws` | Live events: run, plan, job and GPU updates. `llmdyno.watch()`, `dyno.watch()` and the dashboard "
           "listen here; from another machine add `?token=TOKEN`. |", ""]
    for area in sorted(areas):
        out += [f"## {area.capitalize()}", "", "| Route | Python | Command | JavaScript |", "|---|---|---|---|"]
        for op in sorted(areas[area], key=lambda o: (route_table()[o][1], route_table()[o][0])):
            method, path, _where = route_table()[op]
            callables = coverage.get(f"{method} {path}", [])
            py = "<br>".join(python(c) for c in callables)
            cmds = "<br>".join(c for c in dict.fromkeys(cli(c) for c in callables) if c) or "–"
            js = f"`dyno.api.{area}.{_camel(op.split('.', 1)[1])}()`"
            out.append(f"| `{method} {path}` | {py} | {cmds} | {js} |")
        out.append("")
    text = "\n".join(out).rstrip() + "\n"
    return re.sub(r"[ \t]+\n", "\n", text)


PAGES = {"cli.md": render_cli, "web-api.md": render_web_api}


def render_all() -> dict[str, str]:
    os.environ.setdefault("LLMDYNO_DATA", tempfile.mkdtemp(prefix="llmdyno-gen-"))
    os.environ.setdefault("COLUMNS", "120")
    return {name: fn() for name, fn in PAGES.items()}


def main() -> int:
    pages = render_all()
    if "--check" in sys.argv:
        stale = [n for n, text in pages.items()
                 if not (DOCS / n).exists() or (DOCS / n).read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        for n in stale:
            print(f"docs/reference/{n} is out of date: run python scripts/gen_reference_docs.py")
        return 1 if stale else 0
    for name, text in pages.items():
        (DOCS / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote docs/reference/{name} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
